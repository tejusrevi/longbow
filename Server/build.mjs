// Builds the Nakama module: trig tables (from Shared/) + compiled TypeScript.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
// Shared/trig_tables.json holds the canonical tables as IEEE-754 bit patterns.
const raw = JSON.parse(readFileSync(new URL("../Shared/trig_tables.json", import.meta.url)));
const fromBits = (h) => { const v = new DataView(new ArrayBuffer(8)); v.setBigUint64(0, BigInt(h)); return v.getFloat64(0); };
const t = { sin: raw.sinBits.map(fromBits), cos: raw.cosBits.map(fromBits) };
const core = readFileSync(new URL("./build/core.js", import.meta.url), "utf8");
mkdirSync(new URL("./modules", import.meta.url), { recursive: true });
const out = "// GENERATED by Server/build.mjs — do not edit. Source: Server/src/*.ts\n" +
  "var TRIG_SIN = " + JSON.stringify(t.sin) + ";\nvar TRIG_COS = " + JSON.stringify(t.cos) + ";\n" + core;
writeFileSync(new URL("./modules/index.js", import.meta.url), out);
console.log("wrote modules/index.js", out.length, "bytes");
