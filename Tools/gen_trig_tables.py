#!/usr/bin/env python3
"""Generates the canonical sin/cos lookup tables (A6.3).

The tables are the source of truth for client AND server. Values are stored as
IEEE-754 bit patterns so they round-trip exactly in Swift and TypeScript.
Index i covers angle i/10 degrees, i in 0..3600 (3601 entries, 3600 == 0).
"""
import json, math, struct, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def bits(x: float) -> str:
    return "0x%016X" % struct.unpack("<Q", struct.pack("<d", x))[0]

def main():
    n = 3601
    sin = [math.sin(math.radians(i / 10.0)) for i in range(n)]
    cos = [math.cos(math.radians(i / 10.0)) for i in range(n)]
    # Snap exact values so the table is clean at the cardinal angles.
    for i in range(n):
        for tbl in (sin, cos):
            if abs(tbl[i]) < 1e-15: tbl[i] = 0.0
            if abs(tbl[i] - 1) < 1e-15: tbl[i] = 1.0
            if abs(tbl[i] + 1) < 1e-15: tbl[i] = -1.0

    with open(os.path.join(ROOT, "Shared", "trig_tables.json"), "w") as f:
        json.dump({"version": 1, "stepDegrees": 0.1, "count": n,
                   "sinBits": [bits(v) for v in sin],
                   "cosBits": [bits(v) for v in cos]}, f, indent=0)

    out = os.path.join(ROOT, "Core", "Sources", "LongbowCore", "Physics", "TrigTableData.swift")
    with open(out, "w") as f:
        f.write("// GENERATED by Tools/gen_trig_tables.py — do not edit.\n")
        f.write("// Canonical sin/cos tables, index = angle in tenths of a degree (0...3600).\n\n")
        for name, tbl in (("sinTableBits", sin), ("cosTableBits", cos)):
            f.write(f"let {name}: [UInt64] = [\n")
            for k in range(0, n, 6):
                f.write("    " + ", ".join(bits(v) for v in tbl[k:k+6]) + ",\n")
            f.write("]\n\n")
    print("wrote", out)

if __name__ == "__main__":
    main()
